-- Логин не различает регистр.
--
-- ⚠️ Уникальность стояла на самой строке, а поиск шёл точным совпадением. Из-за этого
-- «Shabdan» и «shabdan» были разными людьми, а телефонная клавиатура, которая сама ставит
-- заглавную первую букву, превращала вход с верным паролем в «неверный логин или пароль».
--
-- Регистр сохраняется как набрали: индекс строится по lower(), а само поле не трогается.

-- ⚠️ Сначала снимается ограничение и только потом ставится новый индекс. Обратный порядок
-- не работает: за users_username_key стоит constraint, и `drop index` на него ругается —
-- индекс нельзя убрать, пока ограничение на него опирается.
alter table users drop constraint if exists users_username_key;

create unique index ux_users_username_lower on users (lower(username));

comment on index ux_users_username_lower is
    'Логин уникален без учёта регистра; отображается так, как его набрал владелец';
