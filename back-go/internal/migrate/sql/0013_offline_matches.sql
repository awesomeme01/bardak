-- Оффлайн-партии: игра за настоящим столом, записанная в приложение задним числом.
--
-- ⭐ До этого матч мог родиться только из стола в лобби, и весь прошлый опыт компании —
-- сотни партий за реальным столом — в рейтинге не участвовал вовсе. Оффлайн-матч
-- отличается от онлайнового ровно двумя вещами: у него нет стола и нет лога раздач.
-- Всё остальное — места, ступени навесов, степени проигрыша, рейтинг — считается тем же
-- кодом и лежит в тех же таблицах, иначе история разъехалась бы на две несравнимые.

-- ⚠️ Стол становится необязательным. Это ослабление ограничения, а не расширение схемы:
-- у оффлайн-партии стола не существует, и выдумывать ей фиктивный означало бы засорять
-- лобби записями, за которыми никто никогда не сидел.
alter table matches
    alter column table_id drop not null;

alter table matches
    add column is_offline boolean not null default false,
    add column created_by uuid references users (id);

comment on column matches.is_offline is
    'Партия сыграна за настоящим столом и записана вручную: раздач и лога событий у неё нет';
comment on column matches.created_by is
    'Кто записал оффлайн-партию; у онлайновой пусто — её завёл сам стол';

-- ⚠️ Стол обязателен ровно у онлайновой партии. Без этой проверки ошибка в коде завела бы
-- онлайн-матч без стола, и потерю заметили бы только когда история перестала бы открываться.
alter table matches
    add constraint matches_table_required_online
        check (is_offline or table_id is not null);

-- История игрока читается по match_players, но список оффлайн-партий нужен отдельно —
-- и их заведомо меньшинство, поэтому индекс частичный.
create index idx_matches_offline on matches (started_at desc) where is_offline;
