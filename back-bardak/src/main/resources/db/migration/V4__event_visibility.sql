-- Кому видно событие. Нужно для догона после разрыва (RESYNC) и для реплея.
--
-- ⭐ Лог хранит полную информацию, включая скрытую (какая карта у кого), и отдавать его
-- сырым нельзя (planning/04-db-schema.md). Но и вычислять видимость заново при каждом
-- догоне — значит держать правило в двух местах и однажды разойтись. Поэтому видимость
-- записывается вместе с событием: кто мог его видеть тогда, тот и увидит при догоне.
--
-- null — событие публичное.
alter table match_events
    add column private_to_seat smallint;

comment on column match_events.private_to_seat is
    'Место, которому видно событие; null — всем. Единственный приватный случай — вскрытие скрытой карты (§1.8)';
