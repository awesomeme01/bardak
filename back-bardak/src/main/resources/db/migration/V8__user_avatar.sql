-- Мордочка игрока.
--
-- ⭐ Отдельная колонка, а не `avatar_url`: за столом показывается не картинка, а эмодзи —
-- своё у каждого, чтобы соседей различали не только по имени. Класть эмодзи в колонку
-- с именем «url» значит соврать следующему, кто станет её читать.
alter table users
    add column avatar varchar(8);

comment on column users.avatar is
    'Эмодзи-мордочка; null — выводится из идентификатора игрока';
