package kz.bardak.game.rules;

/**
 * Карта колоды: либо обычная ({@link PipCard}), либо джокер ({@link JokerCard}).
 *
 * <p>Иерархия закрытая намеренно — правила игры разбирают карту исчерпывающим
 * {@code switch}, и компилятор проверяет, что новый вид карты обработан везде.
 */
public sealed interface Card permits PipCard, JokerCard {

    /**
     * Совпадение по рангу — то, что разрешает подкинуть карту к уже лежащим на столе
     * и перевести атаку (§2.1, §2.2).
     *
     * <p>⭐ Ранг джокера — «джокер» (ADR-032): джокер совпадает только с джокером, обычная
     * карта — только с обычной картой того же ранга. Масть при сравнении не участвует.
     */
    boolean sameRankAs(Card other);

    /**
     * Короткий человекочитаемый код карты — {@code 10♥}, {@code Joker-3}. Используется
     * в логах и в тестовых сообщениях, не в протоколе.
     */
    String code();
}
