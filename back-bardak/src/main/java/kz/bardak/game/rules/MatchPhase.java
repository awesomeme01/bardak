package kz.bardak.game.rules;

/**
 * Фазы матча (§4.1). Их всего две: матч либо играется, либо закончен — «между раздачами»
 * отдельным состоянием не является, потому что перераздача происходит в тот же момент,
 * что и подсчёт итога.
 */
public enum MatchPhase {

    /** Идёт раздача. */
    IN_DEAL,

    /** Кому-то навешен джокер, и он не вышел первым (§0.2). */
    MATCH_OVER
}
