package kz.bardak.game.rules;

/**
 * Степени проигрыша (§0.3). Порядок объявления — от самой тяжёлой к самой обычной: когда
 * подходит несколько условий сразу, всегда берётся <b>самая тяжёлая</b>, и это общее
 * правило, а не частный случай.
 *
 * <p>Названия в интерфейсе авторские; в коде — нейтральные константы.
 */
public enum LossDegree {

    /** Джокер, проиграл раздачу, последняя атака — ровно четыре восьмёрки. */
    ROYAL,

    /** Джокер, проиграл раздачу, в последней атаке одна–три восьмёрки. */
    SUPER_MEGA_SUCK,

    /** Джокер навешен картой, проиграл раздачу. */
    SUPER_MEGA_FAIL,

    /** Джокер получен не картой: в навесе был туз, проигрыш раздачи добавил {@code +1}. */
    SUPER_FAIL,

    /** Джокер в навесе, но раздачу игрок не проиграл и первым не вышел. */
    FAIL;

    /** Тяжелее другой степени. Сравнение по порядку объявления, а не по имени. */
    public boolean isHeavierThan(final LossDegree other) {
        return ordinal() < other.ordinal();
    }
}
