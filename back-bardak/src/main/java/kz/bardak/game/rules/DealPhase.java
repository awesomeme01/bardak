package kz.bardak.game.rules;

/**
 * Фазы автомата раздачи (§4.2). Разрешённые переходы — единственный источник правды
 * о том, что игрок может сделать; всё, что не разрешено явно, запрещено.
 */
public enum DealPhase {

    /** Под-seed, перемешивание, сдача, определение козыря. */
    DEALING,

    /** Козырь оказался джокером — бросок кости и выбор масти (§1.10). */
    DICE,

    /** Обладатель права кладёт карту либо пасует. */
    ATTACK,

    /** Защищающийся бьёт, переводит или берёт. */
    DEFEND,

    /**
     * ⭐ Защищающийся объявил «беру», но раунд ещё жив: подкидывающие докидывают ему карты,
     * пока не спасуют (§1.4, ADR-038). Отбиваться и переводить он уже не может, а потолок
     * подкида — только лимит раунда: рука взявшего больше ничего не ограничивает.
     */
    TAKING,

    /** Добор до {@code dealSize} в строгом порядке (§1.4.1). */
    REFILL,

    /** Карты остались у одного игрока — раздача окончена. */
    DEAL_OVER
}
