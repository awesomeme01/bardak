package kz.bardak.game.rules;

/**
 * Почему уровень навесов сдвинулся (§0.1). Сдвиги сочетаются в одной раздаче и друг друга
 * не заменяют, поэтому итоговая разница уровней сама по себе ничего не объясняет: игрок
 * с {@code +1} и {@code −1} выглядит как не сдвинувшийся вовсе.
 */
public enum LevelChangeReason {

    /** Проиграл раздачу — остался с картами (§0.1). */
    LOST_DEAL,

    /** Вышел из раздачи первым. */
    FIRST_OUT,

    /** Добил соперника джокером; награда даётся за каждого и суммируется (ADR-025). */
    FINISHED_OPPONENT,

    /** Шкала кончилась: ступени ниже «летит 6» и выше джокера не существует. */
    SCALE_LIMIT
}
