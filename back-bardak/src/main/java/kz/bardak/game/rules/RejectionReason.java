package kz.bardak.game.rules;

/**
 * Почему ход отклонён. Отдельный перечень, а не текст: причина уходит в протокол, в лог
 * и в тесты, а «ход не прошёл» без причины невозможно ни отладить, ни показать игроку.
 */
public enum RejectionReason {

    /** Ходить пытается не тот, у кого сейчас право (§2.1). */
    NOT_YOUR_TURN,

    /** Карты нет в руке. */
    CARD_NOT_IN_HAND,

    /** Скрытую карту нельзя играть: колода не пуста либо обычные карты ещё есть (§1.8). */
    FACE_DOWN_CARD_NOT_PLAYABLE,

    /** Достигнут потолок атакующих карт в раунде (§1.5). */
    ATTACK_LIMIT_REACHED,

    /** Неотбитых карт станет больше, чем защищающийся способен побить (§1.5). */
    DEFENDER_HAS_TOO_FEW_CARDS,

    /** Такого ранга на столе нет — подкинуть нечего (§1.4). */
    RANK_NOT_ON_TABLE,

    /** Указанной цели на столе нет. */
    TARGET_NOT_ON_TABLE,

    /** По этой атакующей карте уже отбились. */
    TARGET_ALREADY_BEATEN,

    /** Карта не бьёт указанную цель (§1.1.1). */
    CARD_DOES_NOT_BEAT,

    /** Защищающийся уже объявил «беру» — отбиваться и переводить поздно (ADR-038). */
    DEFENDER_ALREADY_TOOK,

    /** Переводы выключены в конфиге стола. */
    TRANSFERS_DISABLED,

    /** Перевод после первой отбитой карты невозможен (§2.2, ADR-031). */
    TRANSFER_AFTER_FIRST_BEAT,

    /** Переводят только картой того же ранга, что лежит в атаке (ADR-031). */
    TRANSFER_RANK_MISMATCH,

    /** Принимающему не хватит карт отбить атаку — перевод запрещён (§2.2). */
    NEXT_PLAYER_HAS_TOO_FEW_CARDS,

    /** Навесы выключены в конфиге стола (§2.3). */
    NAVES_DISABLED,

    /** Себе навесить нельзя — смысл игры в том, чтобы держать уровень ниже (§2.3). */
    CANNOT_HANG_ON_SELF,

    /** Карта не той ступени: навесить можно ровно ту, что летит жертве по её шкале. */
    CARD_NOT_ON_NAVES_SCALE,

    /** Окно навеса сейчас не открыто либо ход не за этим игроком. */
    NOT_IN_HANGING_WINDOW,

    /** Козырь не разыгрывается: масть уже определена нижней картой колоды. */
    TRUMP_NOT_IN_DISPUTE,

    /** Пока козырь не назван, играть нечем: раздача ждёт выбора масти (§1.2, §1.9). */
    TRUMP_NOT_CHOSEN_YET,

    /** «Беру» при пустом столе: брать нечего, и раунд так не закрывается. */
    NOTHING_TO_TAKE,

    /**
     * Пас невозможен: колода пуста, обычных карт нет, и начать раунд можно только вскрыв
     * скрытую карту — выбора у игрока нет (§1.8).
     */
    MUST_REVEAL_FACE_DOWN
}
