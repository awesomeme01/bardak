package kz.bardak;

import org.testcontainers.containers.PostgreSQLContainer;

/**
 * Один Postgres на все интеграционные тесты — «singleton container» из документации
 * Testcontainers.
 *
 * <p>⚠️ {@code @Container} задаёт контейнеру жизнь <b>на класс</b>: JUnit поднимает его перед
 * классом и гасит после. Пятнадцать классов — пятнадцать баз подряд, и на машине с 8 ГБ,
 * отданными Docker, контекст Spring иногда падал не из-за кода, а из-за памяти.
 *
 * <p>Поэтому контейнер намеренно <b>не помечен</b> {@code @Container}: жизненным циклом
 * управляет не JUnit, а JVM — иначе первый же закончившийся класс остановил бы базу под
 * ногами у второго. Убирает его Ryuk, когда прогон закончится.
 *
 * <p>⚠️ Побочное следствие, о котором надо знать при написании новых тестов: <b>база теперь
 * общая на весь прогон</b>. Классы больше не изолированы данными — они изолированы только
 * тем, что берут разные логины, коды столов и идентификаторы. Тест, который считает строки
 * во всей таблице или заводит запись с фиксированным ключом, сломается о соседа. Нужна
 * чистая база — заводить свою схему, а не свой контейнер.
 */
public final class TestPostgres {

    public static final PostgreSQLContainer<?> INSTANCE = new PostgreSQLContainer<>("postgres:16-alpine");

    static {
        INSTANCE.start();
    }

    private TestPostgres() {
    }
}
